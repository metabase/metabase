#!/usr/bin/env python3
"""Convert the isolated H2 reference exported by dev.sqlite-baseline into a SQLite baseline.

Uses only Python's standard library. Never accepts or connects to a live application database.
Run after (dev.sqlite-baseline/export! "/tmp/sqlite-reference.json").
"""
import collections
import json
import hashlib
import pathlib
import re
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]


def ident(value):
    return '"' + value.lower().replace('"', '""') + '"'


def literal(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return '1' if value else '0'
    if isinstance(value, (int, float)):
        return str(value)
    if not isinstance(value, str):
        raise ValueError(f'Unsupported seed value: {type(value)}')
    return "'" + value.replace("'", "''") + "'"


def expression(sql):
    sql = sql.replace('"PUBLIC".', '')
    sql = re.sub(r'"([A-Z_0-9]+)"', lambda m: ident(m[1]), sql)
    return re.sub(r'\bUNKNOWN\b', 'NULL', sql)


def groups(items, key):
    result = collections.defaultdict(list)
    for item in items:
        result[item[key]].append(item)
    return result


def split_compound(sql):
    """Flatten H2's parenthesized UNION operands without touching scalar subqueries."""
    sql = sql.strip()
    tokens = list(re.finditer(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|\(|\)|\bUNION(?: ALL)?\b", sql))
    depth = 0
    splits = []
    outer_end = None
    for token in tokens:
        if token[0] == '(':
            depth += 1
        elif token[0] == ')':
            depth -= 1
            if depth == 0 and outer_end is None:
                outer_end = token.end()
        elif token[0].startswith('UNION') and depth == 0:
            splits.append(token)
    if sql.startswith('(') and outer_end == len(sql):
        return split_compound(sql[1:-1])
    if not splits:
        return sql
    parts = []
    start = 0
    for token in splits:
        parts.extend([split_compound(sql[start:token.start()]), token[0]])
        start = token.end()
    parts.append(split_compound(sql[start:]))
    return '\n'.join(parts)


def view_sql(view):
    if view['table_name'] == 'V_ALERTS':
        return (ROOT / 'resources/sqlite/views/alerts.sql').read_text().strip().rstrip(';')
    sql = expression(split_compound(view['view_definition'])).replace('FETCH FIRST ROW ONLY', 'LIMIT 1')
    sql = re.sub(r'LISTAGG\(([^()]*)\) WITHIN GROUP \(ORDER BY NULL\)', r'GROUP_CONCAT(\1)', sql)
    sql = sql.replace('DATEDIFF(SECOND, "started_at", "ended_at")',
                      '(unixepoch("ended_at") - unixepoch("started_at"))')
    # CONCAT in the reference has SQL-standard NULL-as-empty behavior.
    sql = re.sub(r'CONCAT\(([^()]*)\)',
                 lambda m: '(' + ' || '.join(f"coalesce({s.strip()}, '')" for s in m[1].split(',')) + ')', sql)
    return f'CREATE VIEW {ident(view["table_name"])} AS\n{sql}'


def schema_sql(reference):
    output = ['-- Generated by dev.sqlite-baseline and bin/sqlite/generate_baseline.py.\n'
              '-- Immutable v65 SQLite application database baseline; do not edit after release.\n'
              '-- Seed rows originate exclusively from a fresh, isolated H2 migration.\n'
              'PRAGMA defer_foreign_keys = ON;']
    indexes = []
    output.append('CREATE TABLE secret_id_sequence (id INTEGER PRIMARY KEY CHECK (id = 1), next_id INTEGER NOT NULL);')
    seeds = ['INSERT INTO secret_id_sequence (id, next_id) VALUES (1, 1);']
    for table in reference['tables']:
        name = table['name']
        pk = [p['column_name'] for p in sorted(table['pk'], key=lambda p: p['key_seq'])]
        columns = []
        auto_pk = False
        for column in table['columns']:
            colname = column['column_name']
            datatype = column['data_type']
            auto = column['is_identity'] == 'YES' and pk == [colname]
            generated = column['generation_expression']
            col = ident(colname) + ' '
            if auto:
                assert pk == [colname], (name, colname, pk)
                col += 'INTEGER PRIMARY KEY AUTOINCREMENT'
                auto_pk = True
            else:
                col += ({'CHARACTER VARYING': 'TEXT', 'CHARACTER LARGE OBJECT': 'TEXT',
                         'CHARACTER': 'TEXT', 'VARCHAR_IGNORECASE': 'TEXT COLLATE NOCASE',
                         'BINARY': 'BLOB', 'BINARY LARGE OBJECT': 'BLOB',
                         'DOUBLE PRECISION': 'REAL'}.get(datatype, datatype))
                if generated:
                    col += ' GENERATED ALWAYS AS (' + expression(generated) + ') VIRTUAL'
                if column['is_nullable'] == 'NO':
                    col += ' NOT NULL'
                default = column['column_default']
                if default is not None:
                    if default in ('LOCALTIMESTAMP', 'CURRENT_TIMESTAMP'):
                        default = "(strftime('%Y-%m-%d %H:%M:%f', 'now') || '000')"
                    elif datatype == 'BOOLEAN' and default.upper() in ("'FALSE'", "'TRUE'"):
                        default = '0' if default.upper() == "'FALSE'" else '1'
                    col += ' DEFAULT ' + expression(default)
            columns.append(col)
        if pk and not auto_pk:
            columns.append('PRIMARY KEY (' + ', '.join(map(ident, pk)) + ')')
        for fkname, entries in sorted(groups(table['fk'], 'fk_name').items()):
            entries.sort(key=lambda fk: fk['key_seq'])
            fk = entries[0]
            rules = {0: 'CASCADE', 1: 'RESTRICT', 2: 'SET NULL', 3: 'NO ACTION', 4: 'SET DEFAULT'}
            columns.append('CONSTRAINT ' + ident(fkname) + ' FOREIGN KEY (' +
                           ', '.join(ident(e['fkcolumn_name']) for e in entries) + ') REFERENCES ' +
                           ident(fk['pktable_name']) + ' (' +
                           ', '.join(ident(e['pkcolumn_name']) for e in entries) + ') ON DELETE ' +
                           rules[fk['delete_rule']] + ' ON UPDATE ' + rules[fk['update_rule']])
        output.append('CREATE TABLE ' + ident(name) + ' (\n    ' + ',\n    '.join(columns) + '\n);')
        for idxname, entries in sorted(groups(table['indexes'], 'index_name').items()):
            if not idxname:
                continue
            entries.sort(key=lambda idx: idx['ordinal_position'])
            if [e['column_name'] for e in entries] == pk and not entries[0]['non_unique']:
                continue
            idxname = re.sub(r'_INDEX_[0-9A-F]+$', '', idxname)
            if idxname == 'CONSTRAINT' or idxname.startswith('CONSTRAINT_'):
                idxname = 'idx_baseline_' + name.lower() + '_' + '_'.join(e['column_name'].lower() for e in entries)
            indexes.append('CREATE ' + ('' if entries[0]['non_unique'] else 'UNIQUE ') +
                           'INDEX ' + ident(idxname) + ' ON ' + ident(name) + ' (' +
                           ', '.join(ident(e['column_name']) + (' DESC' if e['asc_or_desc'] == 'D' else '')
                                     for e in entries) + ');')
        seed_columns = [c for c in table['columns'] if not c['generation_expression']]
        rows = sorted(table['rows'], key=lambda row: tuple(str(row[k.lower()]) for k in pk))
        for row in rows:
            values = []
            for c in seed_columns:
                value = row[c['column_name'].lower()]
                if c['column_name'] == 'ENTITY_ID' and name in ('CORE_USER', 'PERMISSIONS_GROUP'):
                    value = hashlib.sha256(f'sqlite-baseline:{name}:{row["id"]}'.encode()).hexdigest()[:20]
                if value is not None and c['data_type'].startswith('TIMESTAMP'):
                    # Avoid embedding generation time in the immutable snapshot.
                    value = '2026-09-24 00:00:00.000000'
                values.append(literal(value))
            seeds.append('INSERT INTO ' + ident(name) + ' (' +
                         ', '.join(ident(c['column_name']) for c in seed_columns) + ') VALUES (' +
                         ', '.join(values) + ');')
    assert not reference['checks'], 'Add check constraint conversion before generating this schema'
    return '\n\n'.join(output + indexes + seeds + [view_sql(v) + ';' for v in reference['views']]) + '\n'


def main():
    reference = json.loads(pathlib.Path(sys.argv[1]).read_text())
    sql = schema_sql(reference)
    # Validate the whole artifact with foreign keys enabled, including every analytics view.
    with sqlite3.connect(':memory:') as conn:
        conn.execute('PRAGMA foreign_keys = ON')
        conn.executescript('BEGIN;\n' + sql + '\nCOMMIT;')
        assert conn.execute('PRAGMA foreign_key_check').fetchall() == []
        assert conn.execute('PRAGMA integrity_check').fetchone() == ('ok',)
        for view in reference['views']:
            conn.execute('SELECT * FROM ' + ident(view['table_name']) + ' LIMIT 1').fetchall()
    target = ROOT / 'resources/sqlite/baseline.sql'
    target.write_text(sql)
    print(f'Wrote {target}: {len(reference["tables"])} tables, {len(reference["views"])} views')


if __name__ == '__main__':
    main()
