import { useMemo, useState } from "react";
import { msgid, ngettext, t } from "ttag";

import {
  useDeleteTransformsFolderMutation,
  useListTransformsQuery,
} from "metabase/api";
import { getErrorMessage } from "metabase/api/utils";
import { useMetadataToasts } from "metabase/common/hooks";
import {
  Form,
  FormErrorMessage,
  FormProvider,
  FormSubmitButton,
} from "metabase/forms";
import { deleteTransformsFolderAndTrack } from "metabase/transforms/analytics";
import {
  Box,
  Button,
  Checkbox,
  FocusTrap,
  Group,
  Icon,
  Modal,
  ScrollArea,
  Stack,
  Text,
} from "metabase/ui";
import { is403Error } from "metabase/utils/errors";
import type { Collection, IconName, TransformTarget } from "metabase-types/api";

import type { CollectionNode, TreeNode } from "./types";
import { buildTreeData, getFolderTransforms } from "./utils";

type DeleteTransformsFolderModalProps = {
  folder: CollectionNode;
  onClose: () => void;
};

/**
 * Deletes a transforms folder, its subfolders and the transforms in them. The output tables stay unless the user
 * chooses to delete them too. There is no undo.
 */
export function DeleteTransformsFolderModal({
  folder,
  onClose,
}: DeleteTransformsFolderModalProps) {
  const { collection } = folder;
  // the list the page shows, from the cache; the dialog follows its refetches while open
  const { data: allTransforms = [] } = useListTransformsQuery({});
  const transforms = useMemo(
    () => getFolderTransforms(folder, allTransforms),
    [folder, allTransforms],
  );
  const [folderTree] = useMemo(
    () => buildTreeData([collection], allTransforms),
    [collection, allTransforms],
  );
  const [deleteTransformsFolder] = useDeleteTransformsFolderMutation();
  const { sendSuccessToast } = useMetadataToasts();
  const [shouldDeleteTables, setShouldDeleteTables] = useState(false);
  const count = transforms.length;
  const hasTransforms = count > 0;

  const handleSubmit = async () => {
    try {
      await deleteTransformsFolderAndTrack({
        deleteFolder: () =>
          deleteTransformsFolder({
            id: collection.id,
            "delete-tables": shouldDeleteTables || undefined,
          }).unwrap(),
        collectionId: collection.id,
        deleteTables: shouldDeleteTables,
      });
    } catch (error) {
      // the form shows the message under the footer, so the user can fix the cause or change the table choice and retry
      throw new Error(
        is403Error(error)
          ? t`You can’t delete "${collection.name}": it holds a transform you can’t edit, or whose type is not enabled on this instance.`
          : getErrorMessage(
              error,
              t`"${collection.name}" could not be deleted`,
            ),
      );
    }
    sendSuccessToast(getSuccessMessage(collection, count, shouldDeleteTables));
    onClose();
  };

  return (
    <Modal
      title={t`Delete ${collection.name} and its contents?`}
      opened
      onClose={onClose}
    >
      <FocusTrap.InitialFocus />
      <FormProvider initialValues={{}} onSubmit={handleSubmit}>
        <Form>
          <Stack gap="xl">
            {hasTransforms ? (
              <>
                <Text>
                  {ngettext(
                    msgid`This will delete this folder, its subfolders, and the ${count} transform inside it. This can’t be undone.`,
                    `This will delete this folder, its subfolders, and the ${count} transforms inside it. This can’t be undone.`,
                    count,
                  )}
                </Text>
                <Checkbox
                  checked={shouldDeleteTables}
                  onChange={(event) =>
                    setShouldDeleteTables(event.currentTarget.checked)
                  }
                  label={t`Also delete the tables generated by these transforms.`}
                  description={t`Queries that use these tables will break.`}
                />
                <DeletedItems
                  folderTree={folderTree}
                  showTables={shouldDeleteTables}
                />
              </>
            ) : (
              <Text>{t`This will delete this folder and its subfolders. This can’t be undone.`}</Text>
            )}
          </Stack>
          <Modal.Footer>
            <FormErrorMessage flex={1} />
            <Button onClick={onClose}>{t`Cancel`}</Button>
            <FormSubmitButton
              label={
                shouldDeleteTables
                  ? t`Delete folder, contents, and tables`
                  : t`Delete folder and contents`
              }
              variant="filled"
              color="negative"
            />
          </Modal.Footer>
        </Form>
      </FormProvider>
    </Modal>
  );
}

type DeletedItemsProps = {
  folderTree: TreeNode;
  showTables: boolean;
};

function DeletedItems({ folderTree, showTables }: DeletedItemsProps) {
  return (
    <Stack gap="sm">
      <Text>{t`Here’s what will be deleted:`}</Text>
      <Box bg="background_page-secondary" bdrs="sm" p="md">
        <ScrollArea.Autosize mah="50vh">
          <DeletedTree node={folderTree} showTables={showTables} />
        </ScrollArea.Autosize>
      </Box>
    </Stack>
  );
}

type DeletedTreeProps = {
  node: TreeNode;
  showTables: boolean;
};

function DeletedTree({ node, showTables }: DeletedTreeProps) {
  // the target, as in the Output table column: the delete drops it whether or not a run created it
  const table = showTables ? node.target : undefined;
  const children = sortTreeNodes(node.children ?? []);
  const hasNestedRows = table != null || children.length > 0;

  return (
    <Stack gap="sm">
      <DeletedRow icon={node.icon} name={node.name} />
      {hasNestedRows && (
        <Stack gap="sm" ml="lg">
          {table != null && (
            <DeletedRow icon="table" name={getTargetTableName(table)} />
          )}
          {children.map((child) => (
            <DeletedTree key={child.id} node={child} showTables={showTables} />
          ))}
        </Stack>
      )}
    </Stack>
  );
}

type DeletedRowProps = {
  icon: IconName;
  name: string;
};

function DeletedRow({ icon, name }: DeletedRowProps) {
  return (
    <Group gap="sm" wrap="nowrap">
      <Icon name={icon} size={16} c="text-secondary" />
      <Text>{name}</Text>
    </Group>
  );
}

/** Folders before transforms, each by name. */
function sortTreeNodes(nodes: TreeNode[]) {
  const rank = (node: TreeNode) => (node.nodeType === "folder" ? 0 : 1);
  return [...nodes].sort(
    (a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name),
  );
}

function getTargetTableName({ schema, name }: TransformTarget) {
  return schema != null ? `${schema}.${name}` : name;
}

function getSuccessMessage(
  collection: Collection,
  count: number,
  deletedTables: boolean,
) {
  const name = collection.name;
  if (count === 0) {
    return t`Deleted "${name}"`;
  }
  if (deletedTables) {
    return ngettext(
      msgid`Deleted "${name}", ${count} transform and its table`,
      `Deleted "${name}", ${count} transforms and their tables`,
      count,
    );
  }
  return ngettext(
    msgid`Deleted "${name}" and ${count} transform`,
    `Deleted "${name}" and ${count} transforms`,
    count,
  );
}
