"""Writes the prototype's results.generated.ts from a finished run.sh work dir."""
import csv
import json
import sys
from pathlib import Path

import duckdb

work, out_file = Path(sys.argv[1]), Path(sys.argv[2])


def read_csv(path):
    with open(path, newline="") as f:
        rows = list(csv.reader(f))
    return {"columns": rows[0], "rows": rows[1:]}


def naive_join():
    con = duckdb.connect(str(work / "demo.duckdb"), read_only=True)
    rel = con.sql((work / "naive_join.sql").read_text())
    rows = [["" if v is None else str(v) for v in row] for row in rel.fetchall()]
    return {"columns": list(rel.columns), "rows": rows}


def text(rel):
    return (work / rel).read_text()


data = {
    "byMonth": read_csv(work / "out/by_month.csv"),
    "byMonthCustomer": read_csv(work / "out/by_month_customer.csv"),
    "naiveJoin": naive_join(),
    "files": {
        "metrics.yml": text("models/marts/metrics.yml"),
        "semantic_models.yml": text("models/marts/semantic_models.yml"),
        "generated.sql": text("out/generated.sql"),
        "naive_join.sql": text("naive_join.sql"),
        "invoices.csv": text("seeds/invoices.csv"),
        "time_entries.csv": text("seeds/time_entries.csv"),
        "customers.csv": text("seeds/customers.csv"),
    },
}

out_file.write_text(
    "// Generated by project/run.sh. Do not edit.\n"
    'import type { DbtExplorationResults } from "./types";\n\n'
    "export const RESULTS: DbtExplorationResults = "
    + json.dumps(data, indent=2)
    + ";\n"
)
