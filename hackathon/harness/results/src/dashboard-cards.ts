// Filters

export type TagName = "corpus" | "scale" | "embedder" | "variant" | "strategy" | "scenario";

export type Filter = {
  label: string;
  slug: string;
  type: "text" | "number";
  /** Dashboard default. Required filters must have one; omit it to open with the filter empty. */
  default?: string | number;
  required?: boolean;
  /** View column the filter compares against. */
  column: string;
  /** Card feeding the dropdown: `value` column, optionally a separate display `label` column. */
  values: { name: string; sql: string; value: string; label?: string };
};

/**
 * Defaults point at the golden corpus, the one the Start-here verdict is about. The Embedding-text filter is
 * required: clearing it would silently average the baseline and variant runs together.
 */
export const FILTERS: Record<TagName, Filter> = {
  corpus: {
    label: "Corpus", slug: "corpus", type: "text", default: "northwind-golden-v1", required: true, column: "corpus_id",
    values: { name: "_values: corpus", value: "corpus_id", sql: "SELECT DISTINCT corpus_id FROM harness_run WHERE corpus_id IS NOT NULL ORDER BY 1" },
  },
  scale: {
    label: "Scale", slug: "scale", type: "number", column: "data_scale",
    values: { name: "_values: scale", value: "data_scale", sql: "SELECT DISTINCT data_scale FROM harness_run WHERE data_scale IS NOT NULL ORDER BY 1" },
  },
  embedder: {
    label: "Embedder", slug: "embedder", type: "text", default: EMBEDDERS[0].embedder, column: "embedder",
    values: { name: "_values: embedder", value: "embedder", sql: "SELECT DISTINCT embedder FROM harness_run WHERE embedder IS NOT NULL ORDER BY 1" },
  },
  variant: {
    label: "Embedding text", slug: "embedding_text", type: "text", default: EMBEDDING_TEXT_VARIANTS[0], required: true,
    column: "embedding_text",
    values: { name: "_values: embedding text", value: "embedding_text", sql: "SELECT DISTINCT embedding_text FROM harness_run ORDER BY 1" },
  },
  strategy: {
    // Required like Embedding text: clearing it would average runs whose catalogue text differs.
    label: "Text strategy", slug: "text_strategy", type: "text", default: "none", required: true, column: "text_strategy",
    values: { name: "_values: text strategy", value: "text_strategy", sql: "SELECT DISTINCT text_strategy FROM harness_run ORDER BY 1" },
  },
  scenario: {
    // A golden scenario with labelled hits, so the drill-down shows highlighting by default.
    label: "Scenario", slug: "scenario", type: "text", default: "concept-01", column: "scenario_id",
    values: {
      name: "_values: scenario", value: "scenario_id", label: "label",
      sql: "SELECT scenario_id, max(scenario_id || ' · ' || query) AS label FROM harness_scenario GROUP BY 1 ORDER BY 1",
    },
  },
};

/** Tags written explicitly in card SQL rather than generated by `where`. */
const EXPLICIT: TagName[] = ["corpus", "scenario"];

type Where = (alias?: string, indent?: string) => string;

function whereFor(tags: TagName[]): Where {
  return (alias = "", indent = "  ") =>
    tags
      .filter((t) => !EXPLICIT.includes(t))
      .map((t) => {
        const col = `${alias && `${alias}.`}${FILTERS[t].column}`;
        // A remembered Scale value must not empty corpora without tiers (golden has NULL scale): BL-27. Safe because
        // cards with the scale tag also filter on one corpus, and no corpus mixes NULL and non-NULL scale.
        const cond = t === "scale" ? `AND (${col} = {{${t}}} OR ${col} IS NULL)` : `AND ${col} = {{${t}}}`;
        return `\n${indent}${FILTERS[t].required ? cond : `[[${cond}]]`}`;
      })
      .join("");
}

