(ns metabase.app-db.snapshot-test-util.generate
  "Writes the checked-in snapshots that [[metabase.app-db.snapshot-test-util/load-snapshot!]] reads.

  Separate from that namespace, rather than the other half of it, because generating needs the migration-test harness
  in [[metabase.app-db.schema-migrations-test.impl]] -- which itself loads snapshots. Keeping the write side here
  leaves the dependency running one way."
  (:require
   [clojure.java.io :as io]
   [clojure.string :as str]
   [metabase.app-db.connection :as mdb.connection]
   [metabase.app-db.custom-migrations :as custom-migrations]
   [metabase.app-db.custom-migrations.util :as custom-migrations.util]
   [metabase.app-db.schema-migrations-test.impl :as impl]
   [metabase.app-db.snapshot-test-util :as snapshot]
   [metabase.app-db.snapshot-test-util.dump :as dump]
   [metabase.app-db.snapshot-test-util.h2 :as snapshot.h2]
   [metabase.app-db.snapshot-test-util.mysql :as snapshot.mysql]
   [metabase.app-db.snapshot-test-util.postgres :as snapshot.postgres]
   [metabase.app-db.test-util :as mdb.test-util]
   [metabase.driver.sql-jdbc.connection :as sql-jdbc.conn]
   [metabase.test.data.interface :as tx]
   [metabase.util :as u]
   [metabase.util.log :as log]))

(set! *warn-on-reflection* true)

(def ^:private flavor->dumper
  "Which [[metabase.app-db.snapshot-test-util.dump/Dumper]] produces each dialect's snapshot. The MariaDB flavors are
  dumped the same way MySQL is, differing only in the flags the dumper carries."
  {:h2                       snapshot.h2/dumper
   :postgres                 snapshot.postgres/dumper
   :mysql                    (snapshot.mysql/dumper :mysql)
   :mariadb                  (snapshot.mysql/dumper :mariadb)
   :mariadb-legacy-timestamp (snapshot.mysql/dumper :mariadb-legacy-timestamp)})

(defn- write-snapshot! [version flavor statements]
  (let [file (io/file "test_resources" (snapshot/resource-path version flavor "sql"))]
    (io/make-parents file)
    (spit file (str "-- Generated by metabase.app-db.snapshot-test-util.generate/generate!. Do not edit by hand.\n"
                    (format "-- Empty %s application DB migrated through %s.\n" (name flavor)
                            (snapshot/through-changeset-id version))
                    snapshot/statement-separator "\n"
                    (str/join (str ";\n" snapshot/statement-separator "\n") statements)
                    ";\n"))
    file))

(defn generate!
  "Regenerate the checked-in snapshot for `db-type`: create a temporary empty app DB, migrate it through
  [[metabase.app-db.snapshot-test-util/through-changeset-id]], and dump the result. Needs `pg_dump` on PATH for
  `:postgres` and `mysqldump` for `:mysql`, plus the usual `MB_<DB>_TEST_*` env vars pointing at a server it may
  create databases on.

  Which file gets written follows [[metabase.app-db.snapshot-test-util/flavor]], so regenerating the MariaDB snapshot
  means running this with `:mysql` while `MB_MYSQL_TEST_*` points at a MariaDB server.

  Deliberately creates its own DB rather than using [[metabase.app-db.schema-migrations-test.impl]]'s harness,
  because the dump tools need the raw connection details that harness hides."
  ([db-type]
   (generate! db-type snapshot/snapshot-version))
  ([db-type version]
   (let [h2?     (= db-type :h2)
         through (snapshot/through-changeset-id version)
         dbdef   {:database-name (format "app_db_snapshot_%05d" (rand-int 100000))
                  :table-definitions []}
         details (delay (tx/dbdef->connection-details db-type :db dbdef))]
     (try
       (when-not h2?
         (tx/create-db! db-type dbdef))
       (let [data-source (mdb.test-util/->ClojureJDBCSpecDataSource
                          (if h2?
                            {:subprotocol "h2", :classname "org.h2.Driver"
                             :subname (format "mem:%s;DB_CLOSE_DELAY=-1" (:database-name dbdef))}
                            (sql-jdbc.conn/connection-details->spec db-type @details)))]
         (with-open [conn (.getConnection ^javax.sql.DataSource data-source)]
           ;; the server decides which dialect this is, not `db-type`: MariaDB is reached as `:mysql`
           (let [flavor (snapshot/flavor conn db-type)]
             (log/info (u/format-color 'blue "Migrating empty %s app db through %s..." flavor through))
             ;; the same bindings [[impl/do-with-temp-empty-app-db]] installs, plus the sample content every test app
             ;; DB is set up without: custom migrations read the app DB through the dynamic var, and must not hand
             ;; work to Quartz against a DB that is about to vanish
             (binding [mdb.connection/*application-db*                (mdb.connection/application-db db-type data-source)
                       custom-migrations.util/*allow-temp-scheduling* false
                       custom-migrations/*create-sample-content*      false]
               (impl/run-migrations-in-range! conn ["v00.00-000" through]))
             (let [dumper (or (flavor->dumper flavor)
                              (throw (ex-info "No dumper for this dialect" {:flavor flavor, :db-type db-type})))
                   file   (write-snapshot! version flavor
                                           (dump/dump-statements dumper (when-not h2? @details) conn))]
               (log/info (u/format-color 'green "Wrote %s" (str file)))
               file))))
       (finally
         (when-not h2?
           (tx/destroy-db! db-type dbdef)))))))
