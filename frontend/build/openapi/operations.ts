export function routeKey(method: string, path: string): string {
  return `${method.toUpperCase()} ${path.replace(/\{[^}]+\}/g, "{}")}`;
}

export interface GeneratedOperation {
  method: string;
  path: string;
  data: string;
  responses?: string;
}

function candidate({ path, data, responses }: GeneratedOperation): string {
  const responsesMember = responses ? `; responses: gen.${responses}` : "";
  return `{ path: ${JSON.stringify(path)}; data: gen.${data}${responsesMember} }`;
}

export function operationsDeclarations(
  operations: GeneratedOperation[],
): string {
  const routes = new Map<string, GeneratedOperation[]>();
  for (const operation of operations) {
    const key = routeKey(operation.method, operation.path);
    routes.set(key, [...(routes.get(key) ?? []), operation]);
  }
  const members = [...routes].map(
    ([key, candidates]) =>
      `  ${JSON.stringify(key)}: readonly [${candidates.map(candidate).join(", ")}];`,
  );
  return [
    "// Generated by frontend/build/openapi/generate-operations.ts.",
    'import type * as gen from "./types.gen";',
    "",
    "export interface Operations {",
    ...members,
    "}",
    "",
  ].join("\n");
}
