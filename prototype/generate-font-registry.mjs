// PROTOTYPE: generates frontend/src/metabase/font-prototype/fonts.generated.ts
// from the Fontsource packages in package.json.
//
// Run after adding or removing a @fontsource-variable/* or @fontsource/* package:
//   node prototype/generate-font-registry.mjs && bunx oxfmt --write frontend/src/metabase/font-prototype
//
// For each font it picks the latin + latin-ext files that cover the most axes
// ("full" > "standard" > "wght"), and records the axes those files contain.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(
  fs.readFileSync(path.join(root, "package.json"), "utf8"),
);
const out = path.join(
  root,
  "frontend/src/metabase/font-prototype/fonts.generated.ts",
);

const SUBSETS = ["latin", "latin-ext"];
const VARIANT_PREFERENCE = ["full", "standard", "wght"];
// Axes that the "standard" files contain, when the font has them.
const STANDARD_AXES = ["wght", "wdth", "slnt", "opsz"];

const packages = Object.keys(pkg.dependencies)
  .filter((name) => name.startsWith("@fontsource"))
  .sort();

const fonts = [];

for (const name of packages) {
  const dir = path.join(root, "node_modules", name);
  const meta = JSON.parse(
    fs.readFileSync(path.join(dir, "metadata.json"), "utf8"),
  );
  const unicode = JSON.parse(
    fs.readFileSync(path.join(dir, "unicode.json"), "utf8"),
  );
  const files = new Set(fs.readdirSync(path.join(dir, "files")));
  const isVariable = name.startsWith("@fontsource-variable/");

  if (isVariable) {
    const variant = VARIANT_PREFERENCE.find((v) =>
      files.has(`${meta.id}-latin-${v}-normal.woff2`),
    );
    if (!variant) {
      console.warn(`skipping ${name}: no latin variable file`);
      continue;
    }
    const axes = Object.entries(meta.variable)
      .filter(([tag]) => tag !== "ital")
      .filter(([tag]) =>
        variant === "full"
          ? true
          : variant === "standard"
            ? STANDARD_AXES.includes(tag)
            : tag === "wght",
      )
      .map(([tag, a]) => ({
        tag,
        min: Number(a.min),
        max: Number(a.max),
        default: Number(a.default),
        step: Number(a.step) || 1,
      }));
    fonts.push({
      id: meta.id,
      family: meta.family,
      category: meta.category,
      kind: "variable",
      files: SUBSETS.filter((s) =>
        files.has(`${meta.id}-${s}-${variant}-normal.woff2`),
      ).map((s) => ({
        subset: s,
        path: `${name}/files/${meta.id}-${s}-${variant}-normal.woff2`,
        unicodeRange: unicode[s],
      })),
      axes,
    });
  } else {
    const weights = meta.weights.filter((w) =>
      files.has(`${meta.id}-latin-${w}-normal.woff2`),
    );
    fonts.push({
      id: meta.id,
      family: meta.family,
      category: meta.category,
      kind: "static",
      staticWeights: weights.map((weight) => ({
        weight,
        files: SUBSETS.filter((s) =>
          files.has(`${meta.id}-${s}-${weight}-normal.woff2`),
        ).map((s) => ({
          subset: s,
          path: `${name}/files/${meta.id}-${s}-${weight}-normal.woff2`,
          unicodeRange: unicode[s],
        })),
      })),
      axes: [],
    });
  }
}

// Relative to the generated file, so the bundler resolves it as a plain file.
const url = (p) =>
  `new URL("../../../../node_modules/${p}", import.meta.url).href`;
const fileLiteral = (f) =>
  `{ subset: "${f.subset}", url: ${url(f.path)}, unicodeRange: "${f.unicodeRange}" }`;

const body = fonts
  .map((f) => {
    const lines = [
      `  {`,
      `    id: "${f.id}",`,
      `    family: "${f.family}",`,
      `    category: "${f.category}",`,
      `    kind: "${f.kind}",`,
      `    axes: ${JSON.stringify(f.axes)},`,
    ];
    if (f.kind === "variable") {
      lines.push(
        `    files: [\n      ${f.files.map(fileLiteral).join(",\n      ")},\n    ],`,
      );
    } else {
      lines.push(
        `    staticWeights: [\n${f.staticWeights
          .map(
            (w) =>
              `      { weight: ${w.weight}, files: [${w.files.map(fileLiteral).join(", ")}] }`,
          )
          .join(",\n")},\n    ],`,
      );
    }
    lines.push(`  },`);
    return lines.join("\n");
  })
  .join("\n");

const source = `// PROTOTYPE: generated by prototype/generate-font-registry.mjs. Do not edit by hand.
import type { PrototypeFont } from "./types";

export const GENERATED_FONTS: PrototypeFont[] = [
${body}
];
`;

fs.writeFileSync(out, source);
console.log(`wrote ${fonts.length} fonts to ${path.relative(root, out)}`);
