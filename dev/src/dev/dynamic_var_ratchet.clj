(ns dev.dynamic-var-ratchet
  "Ratchet on `^:dynamic` var definitions in backend source. Per-file budgets live in
  `dev/dynamic-var-ratchet.edn` and only move down. Adding a dynamic var fails
  `metabase.core.dynamic-var-ratchet-test` — thread an explicit argument (or a ctx map) instead.
  Removing one tightens the budget automatically on your next local test run.

  `seed!` is the escape hatch: it resets every budget to the actual count. Run it from the REPL
  and defend the resulting diff in your PR."
  (:require
   [clojure.java.io :as io]
   [clojure.string :as str]
   [dev.kondo-ratchet :as kondo-ratchet]))

(set! *warn-on-reflection* true)

(def budgets-file
  "Where the per-file budgets live."
  "dev/dynamic-var-ratchet.edn")

(defn source-roots
  "Production source trees the ratchet covers. Test trees are exempt: `binding`-based test
  instrumentation is the legitimate use of dynamic vars."
  []
  (into ["src" "enterprise/backend/src"]
        (comp (map #(io/file % "src"))
              (filter #(.isDirectory ^java.io.File %))
              (map #(.getPath ^java.io.File %)))
        (.listFiles (io/file "modules/drivers"))))

;; Matches the canonical `^:dynamic` and the long-form `^{:dynamic true ...}` attr-map spelling
;; (the map must open on the same line as `:dynamic true` for the long form to count).
(def ^:private dynamic-def-re
  #"\^:dynamic(?![\w'?!*+$-])|\^\{[^}]*:dynamic\s+true")

(defn- clj-file? [^java.io.File f]
  (and (.isFile f)
       (let [n (.getName f)]
         (or (str/ends-with? n ".clj")
             (str/ends-with? n ".cljc")))))

(defn scan
  "Occurrences of dynamic var definitions under `roots`: [{:file \"...\" :line 12} ...].
  String literals and comments are masked first, so `^:dynamic` in a docstring doesn't count."
  ([] (scan (source-roots)))
  ([roots]
   (vec
    (for [root  roots
          file  (file-seq (io/file root))
          :when (clj-file? file)
          :let  [masked (kondo-ratchet/mask-strings-and-comments (slurp file))]
          [line-number line] (map-indexed (fn [i l] [(inc i) l]) (str/split-lines masked))
          _match (re-seq dynamic-def-re line)]
      {:file (.getPath ^java.io.File file), :line line-number}))))

(defn actual-counts
  "occurrences -> sorted map of file -> count."
  [occurrences]
  (into (sorted-map) (update-vals (group-by :file occurrences) count)))

(defn read-budgets []
  (let [f (io/file budgets-file)]
    (if (.exists f)
      (read-string (slurp f))
      (sorted-map))))

(defn drift
  "Map of file -> {:recorded n, :actual n} for every file whose actual dynamic var count differs
  from its budget. Over-budget files include :examples (up to 5 file:line locations). Empty map
  means the ratchet holds."
  [budgets occurrences]
  (let [actual (actual-counts occurrences)]
    (into (sorted-map)
          (keep (fn [file]
                  (let [recorded (get budgets file 0)
                        n        (get actual file 0)]
                    (when (not= recorded n)
                      [file (cond-> {:recorded recorded, :actual n}
                              (> n recorded)
                              (assoc :examples (into []
                                                     (comp (filter #(= file (:file %)))
                                                           (take 5)
                                                           (map #(str (:file %) ":" (:line %))))
                                                     occurrences)))]))))
          (distinct (concat (keys budgets) (keys actual))))))

(defn lowered-budgets
  "Budgets only ever move down: a file below budget shrinks to actual, a file at 0 is dropped,
  an over-budget file keeps its recorded value (failing the test is the test's business), and
  new files are not added."
  [budgets actual]
  (into (sorted-map)
        (keep (fn [[file recorded]]
                (let [n (min recorded (get actual file 0))]
                  (when (pos? n)
                    [file n]))))
        budgets))

(defn render [budgets]
  (let [width (transduce (map (comp count pr-str key)) max 0 budgets)]
    (str ";; Per-file budgets for `^:dynamic` var definitions in backend src. Generated by\n"
         ";; dev.dynamic-var-ratchet — do not hand-edit. Budgets only move down: removing a dynamic\n"
         ";; var tightens this file on your next local test run. Adding one fails\n"
         ";; metabase.core.dynamic-var-ratchet-test: thread an explicit argument (or ctx map)\n"
         ";; instead, or run (dev.dynamic-var-ratchet/seed!) and defend the increase in your PR.\n"
         "{"
         (str/join "\n " (map (fn [[file n]]
                                (format (str "%-" (inc width) "s%d") (pr-str file) n))
                              budgets))
         "}\n")))

(defn fix!
  "Tighten the budgets file to the current actual counts (downward moves only)."
  []
  (spit budgets-file (render (lowered-budgets (read-budgets) (actual-counts (scan))))))

(defn seed!
  "Escape hatch: reset every budget to the actual count, adding new files and raising budgets.
  Defend the resulting diff in your PR."
  []
  (spit budgets-file (render (into (sorted-map) (actual-counts (scan))))))
