(defn- invoke
  "Call `create_autogenerated_dashboard` with `source` the way the agent loop does, in a conversation that holds
  `queries`, in a profile that also has `other-tools` (`search` by default). Return the result, or `{:output <the
  text the model reads> :error {:class :code}}` when the call fails."
  ([source] (invoke source {}))
  ([source queries] (invoke source queries [#'metabot.tools/search-tool]))
  ([source queries other-tools]
   (let [entries (binding [scope/*current-user-scope* api-scope/unrestricted]
                   (metabot.tools/->entries (cons #'metabot.tools/create-autogenerated-dashboard-tool other-tools)
                                            (atom {:state {:queries queries}})
                                            nil
                                            :internal))]
     ((:fn (get entries "create_autogenerated_dashboard")) {:source source}))))

(defn- dashboard
  "The result of a call that created the dashboard titled `title` at `url`."
  [title url]
  {:output     (str "The dashboard has been created and the user has been navigated to view it. Briefly "
                    "acknowledge this (1 sentence) and stop. Do not describe the dashboard contents.")
   :data-parts [{:type      :data
                 :data-type "generated_entity"
                 :data      {:type "dashboard" :url url :title title}}]})

(defn- failure
  "A call that failed with the declared error `code`, and the `lines` that the model reads."
  [code & lines]
  {:output (str/join "\n" lines)
   :error  {:class :recoverable :code code}})

(defn- xray-page
  "Fetch the dashboard for `path` from the X-ray API as `:rasta`."
  [expected-status path]
  (mt/user-http-request :rasta :get expected-status
                        (str "automagic-dashboards/" (str/replace-first path "/auto/dashboard/" ""))))

(defn- venues-query []
  (let [mp (mt/metadata-provider)]
    (lib/query mp (lib.metadata/table mp (mt/id :venues)))))

(deftest dashboard-for-each-source-test
  (mt/with-temp [:model/Table {table-id :id :as table} {:name (mt/random-name) :db_id (mt/id)}
                 :model/Card  {model-id :id}            {:type :model :name "Test model"}
                 :model/Card  {metric-id :id}           {:type :metric :name "Test metric"}
                 :model/Card  {report-id :id}           {:type :question :name "Test report"}]
    (mt/with-current-user (mt/user->id :rasta)
      (testing "the model is told to acknowledge the dashboard in a sentence, and the frontend gets a link to it"
        (is (= (dashboard (or (:display_name table) (:name table)) (str "/auto/dashboard/table/" table-id))
               (invoke {:table_id table-id}))))
      (testing "each kind of source has its own X-ray path"
        (is (= (dashboard "Test model" (str "/auto/dashboard/model/" model-id))
               (invoke {:model_id model-id})))
        (is (= (dashboard "Test metric" (str "/auto/dashboard/question/" metric-id))
               (invoke {:metric_id metric-id})))
        (is (= (dashboard "Test report" (str "/auto/dashboard/question/" report-id))
               (invoke {:report_id report-id}))))
      (testing "a query from the conversation is analyzed as it is"
        (is (=? (dashboard "Dashboard" #"^/auto/dashboard/adhoc/.+")
                (invoke {:query_id "q123"} {"q123" (venues-query)})))))))

(deftest xray-page-test
  (let [venues (venues-query)]
    (mt/with-temp [:model/Card {model-id :id}    {:type :model :dataset_query venues}
                   :model/Card {metric-id :id}   {:type :metric :dataset_query (lib/aggregate venues (lib/count))}
                   :model/Card {question-id :id} {:type :question :dataset_query venues}]
      (let [queries {"q-1"      venues
                     "q-legacy" (lib/->legacy-MBQL venues)
                     "q-model"  (lib/query (mt/metadata-provider)
                                           (lib.metadata/card
                                            (mt/metadata-provider) model-id))
                     "q-staged" (lib/append-stage venues)}]
        (mt/with-current-user (mt/user->id :rasta)
          (doseq [source [{:table_id (mt/id :venues)}
                          {:model_id model-id}
                          {:metric_id metric-id}
                          {:report_id question-id}
                          {:query_id "q-1"}
                          {:query_id "q-legacy"}
                          {:query_id "q-model"}
                          {:query_id "q-staged"}]]
            (testing (str "the X-ray link for " (pr-str source) " returns a dashboard from the API")
              (is (=? {:dashcards seq}
                      (->> (invoke source queries)
                           :data-parts first :data :url
                           (xray-page 200)))))))))))

(deftest log-test
  (testing "the log records the source and leaves out the query text"
    (let [queries {"q-1" (venues-query)}]
      (log.capture/with-log-messages-for-level [logs [metabase.metabot.tools.autogen-dashboard :info]]
        (mt/with-current-user (mt/user->id :rasta)
          (invoke {:query_id "q-1"} queries))
        (is (= ["Creating autogenerated dashboard {:source {:query_id q-1}}"
                "Autogenerated dashboard created {:source {:query_id q-1}}"]
               (map :message (logs))))))))

(deftest unknown-query-id-test
  (testing "a query ID that the conversation doesn't hold fails as it does for the other tools that take one"
    (is (= (failure ::recoverable.common/unknown-query-id
                    "Query \"q-9\" was not found. Available query IDs: \"q-1\"."
                    "Use an available query ID from this conversation.")
           (invoke {:query_id "q-9"} {"q-1" (venues-query)}))))
  (testing "with no query to use, the model is told to build a notebook query, since X-ray refuses a SQL one"
    (is (= (failure ::recoverable.common/unknown-query-id
                    "Query \"q-9\" was not found. Available query IDs: none."
                    "Use `construct_notebook_query` to build a query, then use the returned query ID.")
           (invoke {:query_id "q-9"} {} [#'metabot.tools/construct-notebook-query-tool
                                         #'metabot.tools/create-sql-query-tool]))))
  (testing "only the queries that X-ray can analyze are listed, not the SQL or incomplete ones that it refuses"
    (let [sql (lib/native-query (mt/metadata-provider) "SELECT * FROM VENUES")]
      (is (= (failure ::recoverable.common/unknown-query-id
                      "Query \"q-9\" was not found. Available query IDs: \"q-1\", \"q-legacy\"."
                      "Use an available query ID from this conversation.")
             (invoke {:query_id "q-9"} {"q-1"          (venues-query)
                                        "q-legacy"     (lib/->legacy-MBQL (venues-query))
                                        "q-sql"        sql
                                        "q-sql-legacy" (lib/->legacy-MBQL sql)
                                        "q-sql-staged" (lib/append-stage sql)
                                        "q-draft"      {:database (mt/id)}}))))))

(deftest one-source-test
  (testing "a call that sets no source, or two, is rejected before any source is read"
    (doseq [source [{} {:table_id 1 :model_id 2}]]
      (is (= (failure ::autogen-dashboard/invalid-source
                      "Set exactly one of `table_id`, `model_id`, `metric_id`, `query_id` or `report_id` in `source`.")
             (invoke source)))))
  (testing "a placeholder for an unused source is not a second source"
    (mt/with-temp [:model/Table {table-id :id} {:name (mt/random-name) :db_id (mt/id)}
                   :model/Card  {model-id :id} {:type :model}]
      (mt/with-current-user (mt/user->id :rasta)
        (doseq [[source path] [[{:table_id nil :model_id model-id} (str "/auto/dashboard/model/" model-id)]
                               [{:table_id table-id :model_id 0}   (str "/auto/dashboard/table/" table-id)]
                               [{:table_id 0 :model_id model-id}   (str "/auto/dashboard/model/" model-id)]
                               [{:query_id "" :table_id table-id}  (str "/auto/dashboard/table/" table-id)]]]
          (testing (pr-str source)
            (is (=? {:data-parts [{:data {:url path}}]}
                    (invoke source)))))))))

