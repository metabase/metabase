(deftest unreadable-source-test
  (mt/with-non-admin-groups-no-root-collection-perms
    (mt/with-temp [:model/Collection {coll-id :id}     {}
                   :model/Card       {model-id :id}    {:name "Secret model" :type :model :collection_id coll-id}
                   :model/Card       {metric-id :id}   {:name "Secret metric" :type :metric :collection_id coll-id}
                   :model/Card       {question-id :id} {:name "Secret question" :type :question :collection_id coll-id}
                   :model/Table      {table-id :id}    {:name "Secret table" :db_id (mt/id)}]
      (mt/with-no-data-perms-for-all-users!
        (doseq [[source-key id noun] [[:model_id model-id "Model"]
                                      [:metric_id metric-id "Metric"]
                                      [:report_id question-id "Question"]
                                      [:table_id table-id "Table"]]]
          (testing noun
            (testing "fails for a user who cannot read it, the same way a missing one does"
              (is (= (failure ::recoverable.common/not-found
                              (str noun " " id " was not found. It may not exist, or you may not have access to it.")
                              "Call `search` to find the entity you want and use an id from the results.")
                     (mt/with-current-user (mt/user->id :rasta)
                       (invoke {source-key id})))))
            (testing "still gets an admin a dashboard"
              (is (=? {:data-parts [{:data {:title #"Secret .*"}}]}
                      (mt/with-current-user (mt/user->id :crowberto)
                        (invoke {source-key id})))))))))))

(deftest unrunnable-query-test
  (testing "a user without query permissions gets no X-ray link"
    (let [queries {"q-1" (venues-query)}
          path    (mt/with-current-user (mt/user->id :crowberto)
                    (->> (invoke {:query_id "q-1"} queries)
                         :data-parts first :data :url))]
      (mt/with-no-data-perms-for-all-users!
        (is (= "You don't have permissions to do that."
               (xray-page 403 path)))
        (is (= (failure ::recoverable.common/not-found
                        "Query q-1 was not found. It may not exist, or you may not have access to it."
                        "Call `search` to find the entity you want and use an id from the results.")
               (mt/with-current-user (mt/user->id :rasta)
                 (invoke {:query_id "q-1"} queries))))))))

