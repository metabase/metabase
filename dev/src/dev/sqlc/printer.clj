(ns dev.sqlc.printer
  "Spike: turn `sqlc-gen-json` output into Clojure query fns with Malli result schemas.

  Pipeline: migrated app-db -> pg_dump -> sqlc (+ sqlc-gen-json) -> generate_request.json -> here.
  sqlc resolves `SELECT *` against the catalog and infers expression types, so the JSON already
  carries per-column names, types, and nullability; this namespace only renders them."
  (:require
   [camel-snake-kebab.core :as csk]
   [cheshire.core :as json]
   [clojure.java.io :as io]
   [clojure.string :as str]))

(def ^:private pg-type->malli
  "Postgres type name -> Malli schema. Names arrive bare (`int4`) or schema-qualified
  (`pg_catalog.int4`); `pg-type` strips the qualifier before lookup."
  {"int2"        :int
   "int4"        :int
   "int8"        :int
   "int"         :int
   "bigint"      :int
   "serial"      :int
   "float4"      :double
   "float8"      :double
   "numeric"     'decimal?
   "bool"        :boolean
   "text"        :string
   "varchar"     :string
   "char"        :string
   "citext"      :string
   "uuid"        :uuid
   "date"        'inst?
   "timestamp"   'inst?
   "timestamptz" 'inst?
   "json"        :any
   "jsonb"       :any
   "bytea"       'bytes?})

(defn- pg-type
  "Bare type name for a sqlc column, e.g. `pg_catalog.int4` -> `int4`."
  [col]
  (-> col :type :name (str/split #"\.") last))

(defn- col->malli
  "Malli schema for one sqlc column. Unknown types degrade to :any with a marker so the
  generated file shows what was not mapped rather than silently widening."
  [col]
  (let [base    (get pg-type->malli (pg-type col) :any)
        base    (if (:isArray col) [:sequential base] base)]
    (if (:notNull col)
      base
      [:maybe base])))

(defn- row-schema [columns]
  (into [:map] (map (fn [c] [(keyword (:name c)) (col->malli c)])) columns))

(defn- result-schema
  "Result schema for a query, keyed off the sqlc command: `:one` is a single row or nil,
  `:many` a vector of rows, `:exec` an update count."
  [{:keys [cmd columns]}]
  (let [row (row-schema columns)]
    (case cmd
      ":one"  [:maybe row]
      ":many" [:sequential row]
      ":exec" :int
      :any)))

(defn- unmapped-types
  "Type names in `columns` that have no Malli mapping -- surfaced as a docstring warning."
  [columns]
  (->> columns (map pg-type) (remove pg-type->malli) distinct sort))

(defn- docstring [{:keys [text cmd columns]}]
  (let [unmapped (unmapped-types columns)]
    (str "Generated from SQL. Do not edit.\n\n  "
         (str/replace (str/trim text) #"\n" "\n  ")
         "\n\n  Returns: " (case cmd ":one" "one row or nil" ":many" "a vector of rows"
                                    ":exec" "update count" "unknown")
         (when (seq unmapped)
           (str "\n  UNMAPPED TYPES (schema widened to :any): " (str/join ", " unmapped))))))

(defn- fn-params
  "Parameter symbols for a query. sqlc names a parameter after the column it is compared to;
  unnamed or duplicate names (a param used in two places) fall back to positional argN."
  [parameters]
  (let [named (mapv #(csk/->kebab-case-symbol (or (get-in % [:column :name])
                                                  (str "arg" (:number %))))
                    parameters)]
    (if (= (count named) (count (distinct named)))
      named
      (mapv #(symbol (str "arg" (inc %))) (range (count named))))))

(defn- query->defn-str
  "Render one sqlc query as Clojure source text. Emitted as text rather than via pprint so the
  Malli metadata survives and the docstring keeps real newlines."
  [{:keys [name cmd] :as q}]
  (let [fn-name (csk/->kebab-case-symbol name)
        params  (fn-params (:parameters q))
        schema  (result-schema q)]
    (str "(defn " fn-name "\n"
         "  \"" (str/replace (docstring q) #"\"" "\\\"") "\"\n"
         "  {:malli/schema [:=> [:cat :any" (str/join (repeat (count params) " :any")) "]\n"
         "                  " (pr-str schema) "]}\n"
         "  [db" (str/join (map #(str " " %) params)) "]\n"
         "  (execute! db\n"
         "            [" (pr-str (:text q)) (str/join (map #(str "\n             " %) params)) "]\n"
         "            " (keyword (subs cmd 1)) "))")))

(defn render
  "Read a sqlc generate_request.json and return the generated namespace as a string."
  [json-path ns-sym]
  (let [{:keys [queries]} (json/parse-string (slurp json-path) true)]
    (str ";; GENERATED by dev.sqlc.printer -- do not edit.\n"
         "(ns " ns-sym "\n  (:require [dev.sqlc.runtime :refer [execute!]]))\n\n"
         (str/join "\n\n" (map query->defn-str queries)) "\n")))

(defn -main [json-path ns-sym out-path]
  (io/make-parents out-path)
  (spit out-path (render json-path (symbol ns-sym)))
  (println "wrote" out-path))
