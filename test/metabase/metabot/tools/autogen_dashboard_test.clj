;;; Response Structure Tests

(deftest response-structure-test
  (mt/with-current-user (mt/user->id :rasta)
    (testing "returns instructions for LLM"
      ;; We need to test the structure without actually hitting the database
      ;; Using mt/with-temp for table creation
      (mt/with-temp [:model/Table table {:name (mt/random-name) :db_id (mt/id)}]
        (let [result (autogen-dashboard/create-autogenerated-dashboard
                      {:source {:table_id (:id table)}
                       :memory-atom (atom {:state {}})})]
          (is (string? (:instructions result))))))
    (testing "returns a dashboard generated_entity data part"
      (mt/with-temp [:model/Table table {:name (mt/random-name) :db_id (mt/id)}]
        (let [result (autogen-dashboard/create-autogenerated-dashboard
                      {:source {:table_id (:id table)}
                       :memory-atom (atom {:state {}})})
              part   (first (:data-parts result))
              entity (:data part)]
          (is (contains? result :data-parts))
          (is (= "generated_entity" (:data-type part)))
          (is (= "dashboard" (:type entity)))
          (is (str/starts-with? (:url entity) "/auto/dashboard/"))
          (is (= (or (:display_name table) (:name table)) (:title entity))))))
    (testing "returns user-friendly message"
      (mt/with-temp [:model/Table table {:name (mt/random-name) :db_id (mt/id)}]
        (let [result (autogen-dashboard/create-autogenerated-dashboard
                      {:source {:table_id (:id table)}
                       :memory-atom (atom {:state {}})})]
          (is (string? (get-in result [:structured-output :message])))
          (is (str/includes? (get-in result [:structured-output :message]) "dashboard")))))
    (testing "returns path in structured output"
      (mt/with-temp [:model/Table table {:name (mt/random-name) :db_id (mt/id)}]
        (let [result (autogen-dashboard/create-autogenerated-dashboard
                      {:source {:table_id (:id table)}
                       :memory-atom (atom {:state {}})})]
          (is (string? (get-in result [:structured-output :path]))))))))

