/**
 * Writes the custom expression function list that the AI prompt uses, from
 * the same clause definitions that the expression editor uses.
 *
 *   bun prototype/generate-expression-reference.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  AGGREGATION_FUNCTIONS,
  EXPRESSION_FUNCTIONS,
  EXPRESSION_OPERATORS,
  MBQL_CLAUSES,
} from "../frontend/src/metabase-lib/query/clauses/clauses";
import type {
  ClauseArgDefinition,
  MBQLClauseDefinition,
} from "../frontend/src/metabase-lib/query/clauses/types";

const OUTPUT = join(
  import.meta.dir,
  "../resources/prototype/custom-expression-functions.md",
);

const DATABASE = { engine: "postgres", features: [] };

const CATEGORY_TITLES: Record<string, string> = {
  conversion: "Type conversion",
  string: "Text",
  date: "Date and time",
  math: "Math",
  logical: "Logic and conditions",
  aggregation: "Aggregations (only in aggregation mode)",
  window: "Window functions (only in aggregation mode)",
};

const INFIX = new Set(Object.keys(EXPRESSION_OPERATORS));

type Clauses = Record<string, MBQLClauseDefinition>;

function renderValue(value: unknown): string {
  if (Array.isArray(value)) {
    return value.map(renderValue).join(", ");
  }
  if (typeof value === "string") {
    return JSON.stringify(value);
  }
  if (typeof value === "boolean") {
    return value ? "True" : "False";
  }
  if (value != null && typeof value === "object" && "operator" in value) {
    // Argument examples are `Lib.ExpressionParts`, built with `op()`.
    const { operator, args } = value as { operator: string; args: unknown[] };
    if (operator === "dimension" || operator === "metric") {
      return `[${args[0]}]`;
    }
    // The operator comes from an example, so it is not a typed clause name.
    const clause = (MBQL_CLAUSES as Clauses)[operator];
    const name = clause?.displayName ?? operator;
    if (INFIX.has(operator) && operator !== "not") {
      return args.map(renderValue).join(` ${name} `);
    }
    return `${name}(${args.map(renderValue).join(", ")})`;
  }
  return String(value);
}

function renderSignature(clause: MBQLClauseDefinition) {
  const args = clause.args().map((arg: ClauseArgDefinition) => {
    const name = arg.optional ? `${arg.name}?` : arg.name;
    return `${name}: ${arg.type}`;
  });
  if (clause.multiple && !args.some((arg) => arg.startsWith("…"))) {
    args.push("…");
  }
  return `${clause.displayName}(${args.join(", ")}) → ${clause.type}`;
}

function renderExample(clause: MBQLClauseDefinition) {
  const args = clause.args().flatMap((arg) => {
    if (arg.example === undefined) {
      return [];
    }
    return Array.isArray(arg.example) ? arg.example : [arg.example];
  });
  if (args.length === 0 && clause.args().length > 0) {
    return null;
  }
  return `${clause.displayName}(${args.map(renderValue).join(", ")})`;
}

function cleanText(text: string) {
  return (
    text
      // `now()` reports the current time.
      .replace(/ Currently .*$/, "")
      .replace(/\s+/g, " ")
      .trim()
  );
}

function renderClause(clause: MBQLClauseDefinition) {
  const lines = [`- \`${renderSignature(clause)}\``];
  const description = clause.description?.(DATABASE);
  if (description) {
    lines.push(`  ${cleanText(description)}`);
  }
  // Only the descriptions that list the accepted values say more than the
  // signature.
  for (const arg of clause.args()) {
    if (arg.description && /Choose|"/.test(arg.description)) {
      lines.push(`  \`${arg.name}\`: ${cleanText(arg.description)}`);
    }
  }
  const example = renderExample(clause);
  if (example) {
    lines.push(`  Example: \`${example}\``);
  }
  return lines.join("\n");
}

function renderFunctions() {
  const functions: Clauses = {
    ...EXPRESSION_FUNCTIONS,
    ...AGGREGATION_FUNCTIONS,
  };
  const byCategory = new Map<string, MBQLClauseDefinition[]>();
  for (const clause of Object.values(functions)) {
    const category = clause.category ?? "other";
    byCategory.set(category, [...(byCategory.get(category) ?? []), clause]);
  }
  return Object.entries(CATEGORY_TITLES)
    .filter(([category]) => byCategory.has(category))
    .map(([category, title]) => {
      const clauses = byCategory
        .get(category)!
        .sort((a, b) => a.displayName.localeCompare(b.displayName));
      return `### ${title}\n\n${clauses.map(renderClause).join("\n")}`;
    })
    .join("\n\n");
}

const content = `<!-- Generated by prototype/generate-expression-reference.ts. Do not edit. -->
## Functions

Function names are case-insensitive. \`name?\` is an optional argument, and \`…\` means that you can give more arguments of the same kind.

${renderFunctions()}
`;

writeFileSync(OUTPUT, content);
console.warn(`Wrote ${OUTPUT}`);
