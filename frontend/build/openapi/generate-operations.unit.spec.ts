import { spawnSync } from "child_process";
import fs from "fs";
import os from "os";
import path from "path";

import {
  GENERATED_DECLARATIONS_PATH,
  GENERATED_OPERATIONS_PATH,
  OPENAPI_SPEC_PATH,
} from "./paths";

const SCRIPT = path.join(__dirname, "generate-operations.ts");

type SpecPaths = Record<string, Record<string, { operationId: string }>>;

function requestType(name: string, url: string) {
  return `export type ${name} = { body?: never; path?: never; query?: never; url: "${url}" };`;
}

function responsesType(name: string) {
  return `export type ${name} = { "2XX": { id: number } };`;
}

describe("operations generation", () => {
  let root: string;

  const write = (relativePath: string, contents: string) => {
    const target = path.join(root, relativePath);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, contents);
  };
  const generate = (paths: SpecPaths, declarations: string[]) => {
    write(OPENAPI_SPEC_PATH, JSON.stringify({ paths }));
    write(GENERATED_DECLARATIONS_PATH, declarations.join("\n"));
    return spawnSync("bun", [SCRIPT], { cwd: root, encoding: "utf8" });
  };
  const operationsPath = () => path.join(root, GENERATED_OPERATIONS_PATH);

  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), "operations-generation-"));
  });

  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it("should key each spec operation by its route and point it at its request and responses types", () => {
    const result = generate(
      {
        "/api/card": { post: { operationId: "post-api-card" } },
        "/api/card/{id}": { get: { operationId: "get-api-card-id" } },
        "/api/tiles/{zoom}/{x}/{y}": {
          get: { operationId: "get-api-tiles-zoom-x-y" },
        },
      },
      [
        requestType("PostApiCardData", "/api/card"),
        requestType("GetApiCardIdData", "/api/card/{id}"),
        responsesType("GetApiCardIdResponses"),
        requestType("GetApiTilesZoomXyData", "/api/tiles/{zoom}/{x}/{y}"),
        responsesType("GetApiTilesZoomXyResponses"),
      ],
    );
    expect(result.stderr).toBe("");
    expect(result.status).toBe(0);
    expect(fs.readFileSync(operationsPath(), "utf8")).toBe(
      [
        "// Generated by frontend/build/openapi/generate-operations.ts.",
        'import type * as gen from "./types.gen";',
        "",
        "export interface Operations {",
        '  "POST /api/card": readonly [{ path: "/api/card"; data: gen.PostApiCardData }];',
        '  "GET /api/card/{}": readonly [{ path: "/api/card/{id}"; data: gen.GetApiCardIdData; responses: gen.GetApiCardIdResponses }];',
        '  "GET /api/tiles/{}/{}/{}": readonly [{ path: "/api/tiles/{zoom}/{x}/{y}"; data: gen.GetApiTilesZoomXyData; responses: gen.GetApiTilesZoomXyResponses }];',
        "}",
        "",
      ].join("\n"),
    );
  });

  it("should list both operations under a route when their paths differ only in parameter names", () => {
    const result = generate(
      {
        "/api/database/{id}/schemas": {
          get: { operationId: "get-api-database-id-schemas" },
        },
        "/api/database/{virtual-db}/schemas": {
          get: { operationId: "get-api-database-virtual-db-schemas" },
        },
      },
      [
        requestType(
          "GetApiDatabaseIdSchemasData",
          "/api/database/{id}/schemas",
        ),
        requestType(
          "GetApiDatabaseVirtualDbSchemasData",
          "/api/database/{virtual-db}/schemas",
        ),
      ],
    );
    expect(result.status).toBe(0);
    expect(fs.readFileSync(operationsPath(), "utf8")).toContain(
      '  "GET /api/database/{}/schemas": readonly [{ path: "/api/database/{id}/schemas"; data: gen.GetApiDatabaseIdSchemasData }, { path: "/api/database/{virtual-db}/schemas"; data: gen.GetApiDatabaseVirtualDbSchemasData }];',
    );
  });

  it.each<{
    name: string;
    paths: SpecPaths;
    declarations: string[];
    error: string;
  }>([
    {
      name: "a spec operation has no request type",
      paths: {
        "/api/user": {
          get: { operationId: "get-api-user" },
          post: { operationId: "post-api-user" },
        },
      },
      declarations: [requestType("GetApiUserData", "/api/user")],
      error: `POST /api/user (operationId post-api-user) matches no request type in ${GENERATED_DECLARATIONS_PATH}.`,
    },
    {
      name: "two spec operations match one request type",
      paths: {
        "/api/user": {
          get: { operationId: "get-api-user" },
          post: { operationId: "get_api_user" },
        },
      },
      declarations: [requestType("GetApiUserData", "/api/user")],
      error:
        "GET /api/user (operationId get-api-user) and POST /api/user (operationId get_api_user) both match the request type GetApiUserData.",
    },
    {
      name: "the matching request type has another url",
      paths: { "/api/users": { get: { operationId: "get-api-user" } } },
      declarations: [requestType("GetApiUserData", "/api/user")],
      error:
        "GET /api/users (operationId get-api-user) matches the request type GetApiUserData, whose url is /api/user.",
    },
  ])(
    "should fail without writing the file when $name",
    ({ paths, declarations, error }) => {
      const result = generate(paths, declarations);
      expect(result.status).toBe(1);
      expect(result.stderr.trim()).toBe(error);
      expect(fs.existsSync(operationsPath())).toBe(false);
    },
  );
});
