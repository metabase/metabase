/**
 * Metabase truncates a card's ⓘ tooltip after a few lines, so each tab also ends with a text card spelling out
 * every term its cards use.
 */
/**
 * Height (grid rows) a markdown text card needs at `width` columns, estimated from its text: wrapped lines at
 * roughly 140 characters per full-width line, about 2.1 lines per grid row, plus room for the card's padding.
 */
function fitRows(md: string, width: number): number {
  const perLine = Math.floor(140 * width / 24);
  const lines = md.trim().split("\n").reduce((sum, l) => {
    if (l.trim() === "") return sum + 0.5;
    if (l.startsWith("#")) return sum + 2;
    return sum + Math.ceil(l.replace(/[*`\\]/g, "").length / perLine);
  }, 0);
  return Math.ceil(lines / 2.1) + 2;
}

/** Text cards get the height their text needs, never less than the size they were given. */
const fitted = (i: DashItem): DashItem =>
  i.kind === "text" ? { ...i, size: [i.size[0], Math.max(i.size[1], fitRows(i.text, i.size[0]))] } : i;

/** Tabs whose own text already says how to read them. */
const SELF_EXPLAINED = ["Start here", "Glossary"];

/** Which runs a card shows, in words: whether the Embedder and Scale filters narrow it. */
function filterScope(c: CardItem): string {
  const embedder = c.tags.includes("embedder") ? "the model picked in the Embedder filter" : "every embedding model, as separate rows or series";
  const scale = c.tags.includes("scale") ? "" : ", every size tier";
  return `Shows: ${embedder}${scale}.`;
}

/** "How to read this tab": each visible card's question and how to read it, then what is hidden and why. */
function tabGuide(visible: CardItem[], hidden: DashItem[]): TextItem {
  const lines = visible.map((c) => `- **${c.name}**: ${c.question} ${c.read} *${filterScope(c)}*`);
  const hiddenCards = hidden.filter((i): i is CardItem => i.kind === "card");
  const hiddenLines = hiddenCards.map((c) => `- *${c.name}*: ${c.hidden}`);
  const body = "### How to read this tab\n\n" + lines.join("\n")
    + (hiddenLines.length ? "\n\n**Hidden for now** (they come back when the data exists):\n\n" + hiddenLines.join("\n") : "");
  return text([24, 1], body);
}

export const TABS = TAB_ITEMS.map(({ name, items }) => {
  const visible = items.filter((i) => !i.hidden);
  const cards = visible.filter((i): i is CardItem => i.kind === "card");
  const terms = [...new Set(cards.flatMap((c) => c.terms))];
  return {
    name,
    items: [
      ...(SELF_EXPLAINED.includes(name) || cards.length === 0 ? [] : [tabGuide(cards, items.filter((i) => i.hidden))]),
      ...visible,
      ...(terms.length === 0 ? [] : [text([24, 1], termsMarkdown(terms))]),
    ].map(fitted),
  };
});
