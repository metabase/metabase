import fs from "fs";
import path from "path";

const translated: { text: string; stack?: string }[] = [];
let recording = false;

jest.mock("ttag", () => {
  const record = (
    strings: TemplateStringsArray | string,
    ...values: unknown[]
  ) => {
    const text = typeof strings === "string" ? strings : strings.join("{}");
    if (recording) {
      translated.push({ text, stack: new Error().stack });
    }
    return typeof strings === "string"
      ? strings
      : String.raw({ raw: strings }, ...values);
  };
  const chained = {
    t: record,
    jt: record,
    ngettext: record,
    msgid: record,
    gettext: record,
  };
  return {
    ...chained,
    c: () => chained,
    addLocale: jest.fn(),
    useLocale: jest.fn(),
    setDefaultLang: jest.fn(),
    default: {},
  };
});

const ROOT = path.resolve(__dirname, "../..");

const ROOTS = (
  process.env.I18N_IMPORT_ROOTS ?? "frontend/src,enterprise/frontend/src"
).split(",");

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (
        [
          "__mocks__",
          "__support__",
          "node_modules",
          ".storybook",
          "shared-tests",
          "test",
          "tests",
          // Generated by the SDK package build and gitignored, so not source.
          "cli-snippets-tmp",
          // Node scripts that write build output when they are imported.
          "bin",
        ].includes(entry.name)
      ) {
        continue;
      }
      out.push(...sourceFiles(p));
    } else if (
      /\.tsx?$/.test(entry.name) &&
      !/\.spec\.tsx?$/.test(entry.name) &&
      !/(^|[.-])test-utils\.tsx?$|^test-/.test(entry.name) &&
      !/\.stories\.tsx?$/.test(entry.name) &&
      !entry.name.endsWith(".d.ts")
    ) {
      out.push(p);
    }
  }
  return out;
}

// A module that throws while it is imported hides the translations it would
// have run, so the guard fails on any import error that is not named here.
// None of these modules import ttag, and every module they pull in is visited
// on its own, because the scan walks source files rather than an entry graph.
