(ns metabase-enterprise.semantic-layer-import.ossie.test-util.tpch
  "Regenerates `enterprise/backend/test_resources/semantic_layer_import/ossie/tpch/tpch_sf0_001.edn`: TPC-H at scale
  factor 0.001 as a test dataset definition, in the format of `test/metabase/test/data/dataset_definitions/*.edn`, for
  the end-to-end test in [[metabase-enterprise.semantic-layer-import.ossie.e2e-test]]. Not something that runs
  regularly: only when the columns or the scale change.

  The data is what TPC-H's `dbgen` writes, generated by DuckDB's `tpch` extension (see `tpch.py` next to this file,
  which runs through `uv run --with duckdb`, so `uv` has to be on `PATH` and PyPI reachable): the five tables the
  `tpch-revenue.osi.yaml` semantic model is defined over, without their `*_comment` columns, with TPC-H's keys as the
  tables' primary and foreign keys so that a sync of the loaded dataset knows the joins the import's implicit-join
  dimensions rely on. Table and column names are lower-case, as Postgres stores the unquoted names the model writes
  in upper case; the test maps the model's `SNOWFLAKE_SAMPLE_DATA.TPCH_SF1` onto the dataset with the config's
  `:databases` and `:schema-mapping`. Rows are ordered by primary key, so a regeneration's diff is only what changed.

  The script also computes the model's `net_revenue` metric with plain SQL, at the generated scale and at scale factor
  1. The latter has to be the number Snowflake's TPC-H quickstart documents for the model, 164,360,931,200.40, which
  [[regenerate!]] checks: it is how we know the generated data and the metric's formula are the real thing, since a
  checked-in fixture at scale factor 1 (six million order lines) is out of the question, and the end-to-end test
  checks the imported metric against the same formula at the small scale.

  Run from a REPL at the repo root:

    (metabase-enterprise.semantic-layer-import.ossie.test-util.tpch/regenerate!)"
  (:require
   [clojure.java.io :as io]
   [clojure.java.shell :as sh]
   [clojure.string :as str]
   [metabase-enterprise.semantic-layer-import.dbt.test-util.fixture :as fixture]
   ;; for the `#t` print-method of `LocalDate`, which the dataset EDN is written with
   [metabase.util.date-2]
   [metabase.util.json :as json]
   [metabase.util.malli :as mu]
   [metabase.util.malli.registry :as mr])
  (:import
   (java.time LocalDate)))

(set! *warn-on-reflection* true)

(def dataset-filename
  "Where the dataset is written, relative to the repo root."
  "enterprise/backend/test_resources/semantic_layer_import/ossie/tpch/tpch_sf0_001.edn")

(def scale-factor
  "The TPC-H scale factor of the checked-in dataset: 6,005 order lines, 1,500 orders, 150 customers."
  0.001)

(def sf1-net-revenue
  "The `net_revenue` metric at scale factor 1, as Snowflake's TPC-H quickstart documents it, rounded to cents: the sum
  over every order line not returned of the extended price after discount."
  164360931200.40M)

(def ^:private script
  "The Python script that generates the data, next to this file in the test tree."
  "enterprise/backend/test/metabase_enterprise/semantic_layer_import/ossie/test_util/tpch.py")

(def ^:private keys-by-table
  "Each table's primary key column, and the table each of its foreign key columns points at."
  {"region"   {:pk "r_regionkey"}
   "nation"   {:pk "n_nationkey", :fks {"n_regionkey" :region}}
   "customer" {:pk "c_custkey", :fks {"c_nationkey" :nation}}
   "orders"   {:pk "o_orderkey", :fks {"o_custkey" :customer}}
   ;; lineitem's key is composite, (l_orderkey, l_linenumber), which a dataset definition has no place for
   "lineitem" {:fks {"l_orderkey" :orders}}})

(def ^:private duckdb-type->base-type
  "The Metabase base type of each DuckDB column type TPC-H uses, which is also what Postgres sync gives the loaded
  column."
  {"INTEGER"       :type/Integer
   "BIGINT"        :type/BigInteger
   "DECIMAL(15,2)" :type/Decimal
   "VARCHAR"       :type/Text
   "DATE"          :type/Date})

(mr/def ::field
  "A column as the script describes it."
  [:map {:closed true}
   [:name :string]
   [:type :string]])

(mr/def ::value
  "A cell as the script writes it: a JSON scalar, decimals and dates as strings."
  [:maybe [:or :string number? :boolean]])

(mr/def ::table
  "A table as the script describes it."
  [:map {:closed true}
   [:name   :string]
   [:fields [:sequential ::field]]
   [:rows   [:sequential [:sequential ::value]]]])

(mr/def ::generated
  "What the script writes to stdout; see `tpch.py`."
  [:map {:closed true}
   [:scale_factor    number?]
   [:tables          [:sequential ::table]]
   [:net_revenue     :string]
   [:sf1_net_revenue :string]])

(mu/defn- generate :- ::generated
  "Run the script for `sf` and read what it writes, failing with its output when it does."
  [sf :- number?]
  (let [{:keys [exit out err]} (sh/sh "uv" "run" "--quiet" "--with" "duckdb" "python3" "-I" script
                                      "--sf" (str sf)
                                      :dir (System/getProperty "user.dir"))]
    (when-not (zero? exit)
      (throw (ex-info (format "%s failed (exit %d)" script exit) {:out out, :err err})))
    (json/decode+kw out)))

(mu/defn- edn-value :- :string
  "`value` as the dataset EDN writes it: a decimal as a BigDecimal literal, a date as a `#t` literal, so the loaded
  column has the type the field definition says."
  [base-type :- :keyword
   value     :- ::value]
  (pr-str (case base-type
            :type/Decimal (bigdec ^String value)
            :type/Date    (LocalDate/parse ^String value)
            value)))

(mu/defn- edn-field-definition :- :string
  [table-name :- :string
   {field-name :name, field-type :type} :- ::field]
  (let [base-type (or (duckdb-type->base-type field-type)
                      (throw (ex-info (format "no base type known for DuckDB type %s of %s.%s"
                                              field-type table-name field-name)
                                      {:table table-name, :column field-name, :type field-type})))
        {:keys [pk fks]} (keys-by-table table-name)]
    (str "{:field-name " (pr-str field-name) ", :base-type " base-type
         (when (= field-name pk) ", :pk? true")
         (when-let [fk (get fks field-name)] (str ", :fk " fk))
         "}")))

(mu/defn- edn-table-definition :- :string
  "One table of the dataset EDN, laid out like the checked-in dataset definitions: one field definition and one row
  per line."
  [{table-name :name, :keys [fields rows]} :- ::table]
  (let [base-types (map (comp duckdb-type->base-type :type) fields)]
    (str "[" (pr-str table-name) "\n"
         "  [" (str/join "\n   " (map #(edn-field-definition table-name %) fields)) "]\n"
         "  [" (str/join "\n   " (for [row rows]
                                  (str "[" (str/join ", " (map edn-value base-types row)) "]")))
         "]]")))

(mu/defn- check-sf1 :- :nil
  "Throw unless the script's `net_revenue` at scale factor 1 is [[sf1-net-revenue]] to the cent."
  [{:keys [sf1_net_revenue]} :- ::generated]
  (let [actual (.setScale (bigdec ^String sf1_net_revenue) 2 java.math.RoundingMode/HALF_UP)]
    (when-not (= sf1-net-revenue actual)
      (throw (ex-info (format "net_revenue at scale factor 1 is %s, not the documented %s" actual sf1-net-revenue)
                      {:actual actual, :expected sf1-net-revenue})))))

(mu/defn regenerate! :- :string
  "Regenerate the dataset (see the namespace docstring) and write it to `:out` (default [[dataset-filename]]). Returns
  a one-line summary of what was written, with the small scale's `net_revenue` for the end-to-end test to pin."
  ([]
   (regenerate! {}))

  ([{:keys [out], :or {out dataset-filename}} :- [:map {:closed true}
                                                   [:out {:optional true} :string]]]
   (fixture/check-repo-root)
   (let [{:keys [tables net_revenue] :as generated} (generate scale-factor)]
     (check-sf1 generated)
     (spit (io/file out) (str "[" (str/join "\n " (map edn-table-definition tables)) "]\n"))
     (format "wrote %s: %s; net_revenue at scale factor %s is %s"
             out
             (str/join ", " (for [{table-name :name, :keys [rows]} tables]
                              (format "%s (%d rows)" table-name (count rows))))
             scale-factor
             net_revenue))))
