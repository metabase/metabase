(defn- failure
  "How a `create_autogenerated_dashboard` call with `source` fails, as the agent sees it."
  [source]
  (test-util/tool-failure (tools.legacy/adapt #'autogen-dashboard/create-autogenerated-dashboard-tool)
                          {:source source}))

(deftest create-autogenerated-dashboard-tool-errors-test
  (testing "a query missing from memory goes back to the agent as a failed call"
    (is (= {:class :recoverable
            :code  :metabase.metabot.tools.recoverable.legacy/agent-error
            :text  "Query not found in memory with ID: q-9. Available queries: []"}
           (failure {:query_id "q-9"}))))
  (testing "an unexpected error propagates to the agent loop"
    (mt/with-dynamic-fn-redefs [autogen-dashboard/create-autogenerated-dashboard (fn [_] (throw (ex-info "boom" {})))]
      (is (thrown-with-msg? clojure.lang.ExceptionInfo #"boom"
                            (autogen-dashboard/create-autogenerated-dashboard-tool {:source {:table_id 1}}))))))

(deftest unreadable-source-test
  (mt/with-non-admin-groups-no-root-collection-perms
    (mt/with-temp [:model/Collection {coll-id :id}     {}
                   :model/Card       {model-id :id}    {:name "Secret model" :type :model :collection_id coll-id}
                   :model/Card       {metric-id :id}   {:name "Secret metric" :type :metric :collection_id coll-id}
                   :model/Card       {question-id :id} {:name "Secret question" :type :question :collection_id coll-id}
                   :model/Table      {table-id :id}    {:name "Secret table" :db_id (mt/id)}]
      (mt/with-no-data-perms-for-all-users!
        (doseq [[source-key id noun] [[:model_id model-id "Model"]
                                      [:metric_id metric-id "Metric"]
                                      [:report_id question-id "Question"]
                                      [:table_id table-id "Table"]]]
          (testing noun
            (testing "fails for a user who cannot read it, the same way a missing one does"
              (is (=? {:class :recoverable
                       :code  :metabase.metabot.tools.recoverable.common/not-found
                       :text  (re-pattern (str "(?s)" noun " " id " was not found\\..*"))}
                      (mt/with-current-user (mt/user->id :rasta)
                        (failure {source-key id})))))
            (testing "still gets an admin a dashboard"
              (is (=? {:data-parts [{:data {:title #"Secret .*"}}]}
                      (mt/with-current-user (mt/user->id :crowberto)
                        (autogen-dashboard/create-autogenerated-dashboard-tool {:source {source-key id}})))))))))))

(deftest unavailable-source-test
  (mt/with-temp [:model/Card  {model-id :id} {:type :model :archived true}
                 :model/Table {table-id :id} {:name (mt/random-name) :db_id (mt/id) :active false}]
    (mt/with-current-user (mt/user->id :rasta)
      (testing "an archived source the user can read is in the trash"
        (is (= {:class :recoverable
                :code  ::autogen-dashboard/unavailable-source
                :text  (str "Model " model-id " is in the trash.\n"
                            "Call `search` to find another source and use an id from the results.")}
               (failure {:model_id model-id}))))
      (testing "an inactive table is gone from its database"
        (is (= {:class :recoverable
                :code  ::autogen-dashboard/unavailable-source
                :text  (str "Table " table-id " is no longer in its database.\n"
                            "Call `search` to find another source and use an id from the results.")}
               (failure {:table_id table-id})))))))

(deftest one-source-test
  (testing "a call that sets two sources is rejected before either is read"
    (is (= {:class :recoverable
            :code  ::autogen-dashboard/invalid-source
            :text  "Set exactly one of `table_id`, `model_id`, `metric_id`, `query_id` or `report_id` in `source`."}
           (failure {:table_id 1 :model_id 2}))))
  (testing "a null for an unused source is not a second source"
    (mt/with-temp [:model/Card {model-id :id} {:type :model}]
      (mt/with-current-user (mt/user->id :rasta)
        (is (=? {:structured-output {:path (str "/auto/dashboard/model/" model-id)}}
                (autogen-dashboard/create-autogenerated-dashboard-tool
                 {:source {:table_id nil :model_id model-id}})))))))
