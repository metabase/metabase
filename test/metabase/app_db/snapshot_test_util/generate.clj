(ns metabase.app-db.snapshot-test-util.generate
  "Writes the checked-in snapshots that [[metabase.app-db.snapshot-test-util/load-snapshot!]] reads.

  To regenerate, start a REPL with the `:dev` and `:test` aliases and Docker running, and call [[generate!]] once for
  each of [[metabase.app-db.snapshot-test-util/flavors]].
  The regeneration check in [[metabase.app-db.snapshot-test]] names a stale flavor and the call that rewrites it.

  To move the boundary to a newer changeset:

  1. Rename `test_resources/app_db_snapshots/<version>/`, and set
     [[metabase.app-db.snapshot-test-util/snapshot-version]] to the new name.
  2. In its `meta.edn`, set `:through-changeset-id` to the new boundary and `:executed-at` to that changeset's date.
  3. Regenerate every flavor.
  4. Run [[metabase.app-db.snapshot-test]] against each dialect with `MB_APP_DB_SNAPSHOT_DRIFT_TEST=true`.

  The boundary can go no later than the last changeset with a `vNN.` id until this namespace also writes the snapshot's
  `databasechangelog_version` rows, because loading a snapshot backfills its version from those ids.

  On an arm64 Mac, a fresh container of the amd64 `metabase/mariadb:10.6` image can have a stray `.cache` directory in
  its data directory, which MariaDB lists as a database named `#mysql50#.cache`.
  A v65 precondition that scans every database then fails while generating `:mariadb-legacy-timestamp`.
  Removing `/var/lib/mysql/.cache` in the container once it is ready lets generation finish.
  CI has not hit this.

  Generating needs the migration-test harness in [[metabase.app-db.schema-migrations-test.impl]], which itself loads
  snapshots.
  Keeping the write side in a namespace of its own leaves that dependency running one way."
  (:require
   [clojure.java.io :as io]
   [clojure.string :as str]
   [metabase.app-db.connection :as mdb.connection]
   [metabase.app-db.custom-migrations :as custom-migrations]
   [metabase.app-db.custom-migrations.util :as custom-migrations.util]
   [metabase.app-db.schema-migrations-test.impl :as impl]
   [metabase.app-db.snapshot-test-util :as snapshot]
   [metabase.app-db.snapshot-test-util.dump :as dump]
   [metabase.app-db.snapshot-test-util.h2 :as snapshot.h2]
   [metabase.app-db.snapshot-test-util.mysql :as snapshot.mysql]
   [metabase.app-db.snapshot-test-util.postgres :as snapshot.postgres]
   [metabase.app-db.snapshot-test-util.server :as server]
   [metabase.app-db.test-util :as mdb.test-util]
   [metabase.driver.sql-jdbc.connection :as sql-jdbc.conn]
   [metabase.util :as u]
   [metabase.util.log :as log]))

(set! *warn-on-reflection* true)

(def ^:private flavor->dumper
  "Which [[metabase.app-db.snapshot-test-util.dump/Dumper]] produces each flavor's snapshot.
  The MariaDB flavors are dumped the same way MySQL is, differing only in the flags the dumper carries."
  {:h2                       snapshot.h2/dumper
   :postgres                 snapshot.postgres/dumper
   :mysql                    (snapshot.mysql/dumper :mysql)
   :mariadb                  (snapshot.mysql/dumper :mariadb)
   :mariadb-legacy-timestamp (snapshot.mysql/dumper :mariadb-legacy-timestamp)})

(defn- file-content
  "The text of the snapshot file for `flavor`: a header naming the boundary, then `statements` between separators."
  [version flavor statements]
  (str "-- Generated by metabase.app-db.snapshot-test-util.generate/generate!. Do not edit by hand.\n"
       (format "-- Empty %s application DB migrated through %s.\n" (name flavor)
               (snapshot/through-changeset-id version))
       snapshot/statement-separator "\n"
       (str/join (str ";\n" snapshot/statement-separator "\n") statements)
       ";\n"))

(defn- stamp-changelog!
  "Set `dateexecuted` to `executed-at` and `deployment_id` to [[metabase.app-db.snapshot-test-util/deployment-id]] on
  every DATABASECHANGELOG row, and commit.
  Timestamps in seeded rows are left as the migrations wrote them."
  [^java.sql.Connection conn ^java.time.OffsetDateTime executed-at]
  ;; Liquibase records the wall clock and a fresh random deployment id, which would change the file on every
  ;; regeneration. The execution order survives in `orderexecuted`, which breaks ties in the
  ;; `[dateexecuted orderexecuted]` order Liquibase and [[metabase.app-db.liquibase.versions]] read the changelog in.
  (with-open [stmt (.prepareStatement conn "UPDATE DATABASECHANGELOG SET DATEEXECUTED = ?, DEPLOYMENT_ID = ?")]
    (.setObject stmt 1 (.toLocalDateTime executed-at))
    (.setString stmt 2 snapshot/deployment-id)
    (.executeUpdate stmt))
  (when-not (.getAutoCommit conn)
    (.commit conn)))

(defn- migrate-and-dump!
  "Migrate the empty DB `server` is running through the snapshot boundary and dump it.
  Returns `{:flavor ..., :content ...}`. With a nil `server` it uses a fresh in-memory H2 DB."
  [flavor version server]
  (let [[db-type spec] (if server
                         [(:db-type server)
                          (sql-jdbc.conn/connection-details->spec (:db-type server) (:details server))]
                         [:h2
                          {:subprotocol "h2"
                           :classname   "org.h2.Driver"
                           ;; no DB_CLOSE_DELAY: `conn` stays open through the migration and the dump, and closing it
                           ;; should free the DB rather than leave a migrated copy in the heap
                           :subname     (format "mem:app_db_snapshot_%05d" (rand-int 100000))}])
        through        (snapshot/through-changeset-id version)
        data-source    (mdb.test-util/->ClojureJDBCSpecDataSource spec)]
    (with-open [conn (.getConnection ^javax.sql.DataSource data-source)]
      ;; the image was chosen for a flavor, but only the running server can confirm it is that flavor -- MariaDB is
      ;; reached as `:mysql`, and which MariaDB flavor it is depends on how it handles timestamps
      (let [detected (snapshot/flavor conn db-type)]
        (when-not (= detected flavor)
          (throw (ex-info "The server started for this flavor reports a different one"
                          {:flavor flavor, :detected detected}))))
      (log/info (u/format-color 'blue "Migrating empty %s app db through %s..." flavor through))
      ;; the same bindings [[impl/do-with-temp-empty-app-db]] installs, plus the sample content every test app DB is
      ;; set up without: custom migrations read the app DB through the dynamic var, and must not hand work to Quartz
      ;; against a DB that is about to vanish
      (binding [mdb.connection/*application-db*                (mdb.connection/application-db db-type data-source)
                custom-migrations.util/*allow-temp-scheduling* false
                custom-migrations/*create-sample-content*      false]
        ;; without version tracking: the snapshot then looks like an install from before `databasechangelog_version`
        ;; existed, and whatever loads it backfills its version from the `vNN.` ids, the way such an install is
        ;; upgraded. Migration tests split it into per-major deployments as they would a full replay.
        (impl/run-migrations-in-range! conn ["v00.00-000" through] {:track-versions? false}))
      (stamp-changelog! conn (snapshot/executed-at version))
      {:flavor  flavor
       :content (file-content version flavor
                              (dump/dump-statements (flavor->dumper flavor) server conn))})))

(defn dump-snapshot!
  "Migrate an empty app DB of `flavor` through [[metabase.app-db.snapshot-test-util/through-changeset-id]] and dump it.
  Returns `{:flavor ..., :content ...}`: the dialect it was taken as, and the text its snapshot file should hold.
  It writes nothing, so a test can ask what regenerating would produce without touching what is checked in.

  Every flavor but `:h2` runs against a server this starts itself, from the image
  [[metabase.app-db.snapshot-test-util.server]] pins for it.
  All it needs is a working `docker`, with no `MB_<DB>_TEST_*` settings and no server already running."
  ([flavor]
   (dump-snapshot! flavor snapshot/snapshot-version))
  ([flavor version]
   (if (= flavor :h2)
     (migrate-and-dump! flavor version nil)
     (server/do-with-server! flavor #(migrate-and-dump! flavor version %)))))

(defn generate!
  "Regenerate the checked-in snapshot for `flavor` and return the file written.

  The flavor is the dialect the file is for, one of [[metabase.app-db.snapshot-test-util/flavors]].
  There is a file per flavor, so regenerating the MariaDB one means passing `:mariadb`, not the `:mysql` it is reached
  as.
  See [[dump-snapshot!]] for what this needs."
  ([flavor]
   (generate! flavor snapshot/snapshot-version))
  ([flavor version]
   (let [{:keys [flavor content]} (dump-snapshot! flavor version)
         file                     (io/file "test_resources" (snapshot/resource-path version flavor "sql"))]
     (io/make-parents file)
     (spit file content)
     (log/info (u/format-color 'green "Wrote %s" (str file)))
     file)))
