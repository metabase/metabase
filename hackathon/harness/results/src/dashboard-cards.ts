export type CardItem = {
  kind: "card";
  name: string;
  description?: string;
  display: string;
  tags: TagName[];
  size: [number, number];
  settings?: Record<string, unknown>;
  sql: string;
  /** Glossary terms the card uses: explained in its description and in its tab's "Terms on this tab" card. */
  terms: Term[];
  /** The question the card answers, in plain words. Leads its description and its tab's "How to read" card. */
  question: string;
  /** How to read the card, one or two sentences. */
  read: string;
  /** Why the card is hidden for now (degenerate on today's data). Its code stays; the tab's "How to read" card lists it. */
  hidden?: string;
};
export type TextItem = { kind: "text"; size: [number, number]; text: string; hidden?: string };
export type DashItem = CardItem | TextItem;

/** `terms` are the glossary entries the card uses; their one-line explainers are appended to its description. */
function card({ terms, question, read, ...spec }: Omit<CardItem, "kind" | "size" | "sql"> & {
  size?: [number, number]; sql: (where: Where) => string;
}): CardItem {
  return {
    ...spec, kind: "card", size: spec.size ?? [12, 6], terms, question, read,
    description: explain([question, read, spec.description].filter(Boolean).join(" "), terms),
    sql: spec.sql(whereFor(spec.tags)),
  };
}

